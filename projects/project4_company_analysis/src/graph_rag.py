"""
Graph RAG: Graph-enhanced Retrieval Augmented Generation.

Implements two search strategies from Microsoft's GraphRAG paper:
- Local Search: Entity-focused, uses graph neighborhood
- Global Search: Community-level, uses summarized community reports

Also implements hybrid search combining graph traversal with vector retrieval.
"""

import json
from dataclasses import dataclass, field
from typing import Any, Optional

import networkx as nx
from loguru import logger
from openai import OpenAI
from tenacity import retry, stop_after_attempt, wait_exponential

from .config import config
from .knowledge_graph_builder import KnowledgeGraphBuilder


@dataclass
class EntityContext:
    """Context about an entity and its graph neighborhood."""
    entity_name: str
    entity_type: str
    properties: dict
    neighbors: list[dict]  # [{name, type, relationship, properties}]
    community_id: Optional[int] = None
    community_summary: Optional[str] = None


@dataclass
class CommunityReport:
    """A summarized report for a graph community."""
    community_id: int
    title: str
    summary: str
    entities: list[str]
    key_findings: list[str]
    relevance_score: float = 0.0


@dataclass
class GraphRAGAnswer:
    """Answer generated by GraphRAG with provenance."""
    answer: str
    search_type: str  # local, global, hybrid
    entities_used: list[str]
    communities_used: list[int]
    context_snippets: list[str]
    confidence: float


